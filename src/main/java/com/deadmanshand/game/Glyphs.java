package com.deadmanshand.game;

/** A blocky three-by-five font, for writing in blocks on walls: room numbers, names on roofs. */
final class Glyphs {
    private static final String[] DIGITS = {
            "###,#.#,#.#,#.#,###", "..#,..#,..#,..#,..#", "###,..#,###,#..,###", "###,..#,###,..#,###", "#.#,#.#,###,..#,..#",
            "###,#..,###,..#,###", "###,#..,###,#.#,###", "###,..#,..#,..#,..#", "###,#.#,###,#.#,###", "###,#.#,###,..#,###"};
    private static final String[] LETTERS = {
            ".#.,#.#,###,#.#,#.#", "##.,#.#,##.,#.#,##.", "###,#..,#..,#..,###", "##.,#.#,#.#,#.#,##.", "###,#..,##.,#..,###",
            "###,#..,##.,#..,#..", "###,#..,#.#,#.#,###", "#.#,#.#,###,#.#,#.#", "###,.#.,.#.,.#.,###", "..#,..#,..#,#.#,###",
            "#.#,#.#,##.,#.#,#.#", "#..,#..,#..,#..,###", "#.#,###,###,#.#,#.#", "##.,#.#,#.#,#.#,#.#", "###,#.#,#.#,#.#,###",
            "###,#.#,###,#..,#..", "###,#.#,#.#,###,..#", "###,#.#,##.,#.#,#.#", "###,#..,###,..#,###", "###,.#.,.#.,.#.,.#.",
            "#.#,#.#,#.#,#.#,###", "#.#,#.#,#.#,#.#,.#.", "#.#,#.#,###,###,#.#", "#.#,#.#,.#.,#.#,#.#", "#.#,#.#,.#.,.#.,.#.",
            "###,..#,.#.,#..,###"};
    private static final String[] BLANK = {"...", "...", "...", "...", "..."};

    private Glyphs() {
    }

    /** Five rows of three: '#' is a block. */
    static String[] of(char c) {
        if (c >= '0' && c <= '9') {
            return DIGITS[c - '0'].split(",");
        }
        char u = Character.toUpperCase(c);
        if (u >= 'A' && u <= 'Z') {
            return LETTERS[u - 'A'].split(",");
        }
        return BLANK;
    }
}
